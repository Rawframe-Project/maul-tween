# A fuzz target's seeds as a C header its test replays: the inputs of a
# minimized corpus (libFuzzer's -merge=1 with -use_counters=0, one input
# per new edge) in test/generated/fuzz_seeds_<target>.h, sorted by their
# bytes so the header is the same for the same set. ctest replays them
# on every platform before the target's fixed random inputs; a campaign
# starts from them again with `extract`.
#
# usage: fuzz_seeds.py write <target> <corpus dir>
#        fuzz_seeds.py extract <target> <dir>

import hashlib
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")


def header_path(target):
    return os.path.join(ROOT, "test", "generated", "fuzz_seeds_" + target + ".h")


def write(target, corpus):
    seeds = sorted(open(os.path.join(corpus, name), "rb").read()
                   for name in os.listdir(corpus))
    seeds = [s for s in seeds if s]
    guard = "MTWN_FUZZ_SEEDS_" + target.upper() + "_H"
    lines = [
        "// SPDX-License-Identifier: MIT",
        "// Copyright (c) 2026 Sirac Ozmen",
        "//",
        "// Generated by tools/fuzz_seeds.py; do not edit. fuzz_" + target + "'s seeds,",
        "// one input per edge of a minimized corpus, end to end.",
        "// clang-format off",
        "",
        "#ifndef " + guard,
        "#define " + guard,
        "",
        "static const uint8_t s_seedBytes[] = {",
    ]
    data = b"".join(seeds)
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",")
    lines += ["};", "", "// Where each seed ends in s_seedBytes.", "static const uint32_t s_seedEnds[] = {"]
    end = 0
    ends = []
    for s in seeds:
        end += len(s)
        ends.append(str(end) + "u")
    for i in range(0, len(ends), 12):
        lines.append("    " + ", ".join(ends[i:i + 12]) + ",")
    lines += ["};", "", "#endif", ""]
    with open(header_path(target), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote %d seeds, %d bytes, to %s" % (len(seeds), len(data),
                                              os.path.normpath(header_path(target))))


def extract(target, out):
    text = open(header_path(target), encoding="utf-8").read()
    body = text.split("s_seedBytes[] = {", 1)[1].split("};", 1)[0]
    data = bytes(int(x, 16) for x in re.findall(r"0x([0-9a-f]{2})", body))
    ends_body = text.split("s_seedEnds[] = {", 1)[1].split("};", 1)[0]
    ends = [int(x) for x in re.findall(r"(\d+)u", ends_body)]
    os.makedirs(out, exist_ok=True)
    start = 0
    for end in ends:
        seed = data[start:end]
        name = hashlib.sha1(seed).hexdigest()
        with open(os.path.join(out, name), "wb") as f:
            f.write(seed)
        start = end
    print("extracted %d seeds to %s" % (len(ends), out))


def main():
    if len(sys.argv) != 4 or sys.argv[1] not in ("write", "extract"):
        print(__doc__ or "usage: fuzz_seeds.py write|extract <target> <dir>")
        return 2
    (write if sys.argv[1] == "write" else extract)(sys.argv[2], sys.argv[3])
    return 0


if __name__ == "__main__":
    sys.exit(main())
