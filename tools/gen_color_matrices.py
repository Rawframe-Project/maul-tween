def decimal(value):
    if isinstance(value, Fraction):
        return D(value.numerator) / D(value.denominator)
    return D(value)


def multiply(a, b):
    return [[sum(decimal(a[i][k]) * decimal(b[k][j]) for k in range(3)) for j in range(3)]
            for i in range(3)]


def nearest(value):
    # Python's float of a decimal string is correctly rounded.
    return float(str(value))


def table(name, rows, note):
    out = [f"// {note}", f"static const double {name}[3][3] = {{"]
    for row in rows:
        out.append("    {" + ", ".join(nearest(decimal(v)).hex() for v in row) + "},")
    out.append("};")
    return out


def render():
    head = [
        "// SPDX-License-Identifier: MIT",
        "// Copyright (c) 2026 Sirac Ozmen",
        "//",
        "// Generated by tools/gen_color_matrices.py; do not edit. The color",
        "// conversion matrices from CSS Color 4's",
        "// conversions.js, multiplied to 80 digits and rounded once to binary64.",
        "// clang-format off",
        "",
        "#ifndef MTWN_COLOR_MATRICES_H",
        "#define MTWN_COLOR_MATRICES_H",
        "",
    ]
    body = []
    body += table("s_linearSrgbToLms", multiply(XYZ_TO_LMS, SRGB_TO_XYZ),
                  "Linear sRGB to LMS: XYZ to LMS times sRGB to XYZ.")
    body += table("s_lmsToLinearSrgb", multiply(XYZ_TO_SRGB, LMS_TO_XYZ),
                  "LMS to linear sRGB: XYZ to sRGB times LMS to XYZ.")
    body += table("s_lmsToOklab", LMS_TO_OKLAB, "The cube roots of LMS to Oklab.")
    body += table("s_oklabToLms", OKLAB_TO_LMS, "Oklab to the cube roots of LMS.")
    return "\n".join(head + body + ["", "#endif", ""])


def main():
    text = render()
    if len(sys.argv) > 1 and sys.argv[1] == "--check":
        current = open(PATH, encoding="utf-8").read() if os.path.exists(PATH) else ""
        if current != text:
            print("src/generated/color_matrices.h is stale: run tools/gen_color_matrices.py")
            return 1
        print("color matrices: current")
        return 0
    with open(PATH, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote " + os.path.normpath(PATH))
    return 0


if __name__ == "__main__":
    sys.exit(main())
