# An independent reference for the cycles a scaled time is in with a
# repeat delay (mtwnCycleOf, src/timing_internal.h), where the position
# passes the doubles: the same double steps (position, quotient, floor,
# time into the cycle) with an exponent without bounds, each operation
# rounded to 53 bits in exact rationals. Where the quotient passes the
# doubles, or the time into the cycle lies outside a cycle (a start past
# 2^53 cycles rounds the count by more than one), the case says the
# library keeps its result as before: an infinite count. It writes
# test/generated/cycle_cases.h: inputs from its own SplitMix64 whose
# position overflows, and the pinned cases, with the results.
#
# usage: cycle_oracle.py [--check]

import math
import os
import sys
from fractions import Fraction

PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "test",
                    "generated", "cycle_cases.h")

DBL_MAX = sys.float_info.max
COUNT = 384


class SplitMix64:
    def __init__(self, seed):
        self.state = seed & (2 ** 64 - 1)

    def next(self):
        self.state = (self.state + 0x9E3779B97F4A7C15) & (2 ** 64 - 1)
        z = self.state
        z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & (2 ** 64 - 1)
        z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & (2 ** 64 - 1)
        return z ^ (z >> 31)

    def unit(self):
        return (self.next() >> 11) * 2.0 ** -53

    def big(self):
        kind = self.next() % 5
        if kind == 0:
            return DBL_MAX * self.unit()
        if kind == 1:
            return math.ldexp(1.0 + self.unit(), int(self.next() % 1100) - 80)
        if kind == 2:
            return float(math.floor(self.unit() * 10.0))
        if kind == 3:
            return math.ldexp(1.0, int(self.next() % 1023))
        return self.unit() * 5.0


def rounded(x):
    # x rounded to 53 bits, to nearest, ties to even, with no bound on the
    # exponent.
    if x == 0:
        return Fraction(0)
    sign = -1 if x < 0 else 1
    x = abs(x)
    e = x.numerator.bit_length() - x.denominator.bit_length()
    if x < Fraction(2) ** e:
        e -= 1
    scale = Fraction(2) ** (e - 52)
    q = x / scale
    whole = q.numerator // q.denominator
    rest = q - whole
    if rest > Fraction(1, 2) or (rest == Fraction(1, 2) and whole % 2 == 1):
        whole += 1
    return sign * whole * scale


def overflows(scaled, start, duration, cycle):
    first = math.floor(start)
    position = scaled + first * cycle + (start - first) * duration
    return math.isinf(position) and math.isfinite(scaled)


def cycle_of(scaled, start, duration, cycle):
    # The count and the time into its cycle, or None where the library
    # keeps its result as before.
    first = Fraction(math.floor(start))
    s, d, c = Fraction(scaled), Fraction(duration), Fraction(cycle)
    frac = Fraction(start) - first
    position = rounded(rounded(s + rounded(first * c)) + rounded(frac * d))
    quotient = rounded(position / c)
    k = quotient.numerator // quotient.denominator
    k = max(k, first)
    within = rounded(position - rounded(k * c))
    if quotient > Fraction(DBL_MAX) or abs(within) > c:
        return None
    return float(k), float(within)


def cases():
    out = []
    # The case the fuzz target found: 2.5 iterations of about 1e308 s
    # before the first, with a repeat delay. Iteration 2, half way in.
    out.append((0.7, 2.5, 1e308, 1e308 + 0.08203125))
    # Kept: three quarters of the largest double into 2^1023 cycles of
    # 1 s, whose quotient passes the doubles.
    out.append((0.75 * DBL_MAX, 2.0 ** 1023, 0.5, 1.0))
    # Kept: a start of 2^173 cycles of about 2^903 s, whose count rounds by
    # more than one.
    out.append((float.fromhex("0x1.0579ef3b29344p+1023"), 2.0 ** 173,
                float.fromhex("0x1.6a7541f2ca94p+851"), float.fromhex("0x1.83b9c3688af27p+903")))
    rng = SplitMix64(0x6379636C65)
    while len(out) < COUNT:
        scaled, start, duration, delay = rng.big(), rng.big(), rng.big(), rng.big()
        if not (duration > 0 and delay > 0 and math.isfinite(duration + delay)):
            continue
        cycle = duration + delay
        if overflows(scaled, start, duration, cycle):
            out.append((scaled, start, duration, cycle))
    return out


def number(value):
    if math.isnan(value):
        return "NAN_CASE"
    if math.isinf(value):
        return "HUGE_VAL" if value > 0 else "-HUGE_VAL"
    return float(value).hex()


def render():
    lines = [
        "// SPDX-License-Identifier: MIT",
        "// Copyright (c) 2026 Sirac Ozmen",
        "//",
        "// Generated by tools/oracle/cycle_oracle.py; do not edit. Scaled",
        "// times whose position with a repeat delay passes the doubles, and",
        "// the cycle and time into it an exponent without bounds gives; an",
        "// infinite cycle where the library keeps its result as before.",
        "// clang-format off",
        "",
        "#ifndef MTWN_CYCLE_CASES_H",
        "#define MTWN_CYCLE_CASES_H",
        "",
        "#define NAN_CASE ((double)NAN)",
        "",
        "static const CycleCase s_cycleCases[] = {",
    ]
    for scaled, start, duration, cycle in cases():
        assert overflows(scaled, start, duration, cycle)
        result = cycle_of(scaled, start, duration, cycle)
        k, within = result if result is not None else (math.inf, math.nan)
        values = ", ".join(number(v) for v in (scaled, start, duration, cycle, k, within))
        lines.append(f"    {{{values}}},")
    lines += ["};", "", "#endif", ""]
    return "\n".join(lines)


def main():
    text = render()
    if len(sys.argv) > 1 and sys.argv[1] == "--check":
        current = open(PATH, encoding="utf-8").read() if os.path.exists(PATH) else ""
        if current != text:
            print("test/generated/cycle_cases.h is stale: run tools/oracle/cycle_oracle.py")
            return 1
        print("cycle cases: current")
        return 0
    os.makedirs(os.path.dirname(PATH), exist_ok=True)
    with open(PATH, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote " + os.path.normpath(PATH))
    return 0


if __name__ == "__main__":
    sys.exit(main())
